#!/bin/sh
# Cross-compiles a static, HTTP-only libcurl (with gzip via ppc-zlib) for the
# Wii using devkitPPC + libogc's BSD socket layer. Output: third_party/wii/
set -eu

CURL_VER=8.23.0
CURL_SHA256=e3de77cfa6367083c776a26647fc9f633b538c06c3baa73d931a252ac8f72b49

: "${DEVKITPRO:=/opt/devkitpro}"
: "${DEVKITPPC:=$DEVKITPRO/devkitPPC}"
export DEVKITPRO DEVKITPPC

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC=$ROOT/third_party/src
BUILD=$ROOT/third_party/build/curl
PREFIX=$ROOT/third_party/wii

if [ -f "$PREFIX/lib/libcurl.a" ] && [ "${1:-}" != "--force" ]; then
	echo "libcurl already built in $PREFIX (use --force to rebuild)"
	exit 0
fi

mkdir -p "$SRC"
TARBALL=$SRC/curl-$CURL_VER.tar.gz
if [ ! -f "$TARBALL" ]; then
	curl -fsSL -o "$TARBALL.part" "https://curl.se/download/curl-$CURL_VER.tar.gz"
	mv "$TARBALL.part" "$TARBALL"
fi
echo "$CURL_SHA256  $TARBALL" | shasum -a 256 -c -

rm -rf "$SRC/curl-$CURL_VER" "$BUILD"
tar -xzf "$TARBALL" -C "$SRC"

# libogc declares getaddrinfo/select/getpeername but does not implement them,
# so steer curl to the gethostbyname resolver and poll().
cmake -S "$SRC/curl-$CURL_VER" -B "$BUILD" \
	-DCMAKE_TOOLCHAIN_FILE="$DEVKITPRO/cmake/Wii.cmake" \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX="$PREFIX" \
	-DBUILD_SHARED_LIBS=OFF -DBUILD_STATIC_LIBS=ON \
	-DBUILD_CURL_EXE=OFF -DBUILD_LIBCURL_DOCS=OFF -DBUILD_MISC_DOCS=OFF -DENABLE_CURL_MANUAL=OFF \
	-DBUILD_TESTING=OFF -DBUILD_EXAMPLES=OFF \
	-DHTTP_ONLY=ON \
	-DCURL_ENABLE_SSL=OFF -DCURL_USE_OPENSSL=OFF \
	-DCURL_ZLIB=ON -DCURL_BROTLI=OFF -DCURL_ZSTD=OFF \
	-DUSE_NGHTTP2=OFF -DUSE_LIBIDN2=OFF -DCURL_USE_LIBPSL=OFF -DCURL_USE_LIBSSH2=OFF \
	-DCURL_USE_GSSAPI=OFF -DUSE_LIBRTMP=OFF \
	-DENABLE_IPV6=OFF -DENABLE_THREADED_RESOLVER=OFF -DENABLE_ARES=OFF -DENABLE_UNIX_SOCKETS=OFF \
	-DCURL_DISABLE_COOKIES=ON -DCURL_DISABLE_NETRC=ON -DCURL_DISABLE_ALTSVC=ON -DCURL_DISABLE_HSTS=ON \
	-DCURL_DISABLE_PROXY=ON -DCURL_DISABLE_NTLM=ON -DCURL_DISABLE_KERBEROS_AUTH=ON \
	-DCURL_DISABLE_NEGOTIATE_AUTH=ON -DCURL_DISABLE_AWS=ON -DCURL_DISABLE_SOCKETPAIR=ON \
	-DCURL_DISABLE_INSTALL=OFF \
	-DHAVE_GETADDRINFO=0 -DHAVE_FREEADDRINFO=0 -DHAVE_GETADDRINFO_THREADSAFE=0 \
	-DHAVE_SELECT=0 -DHAVE_POLL=1 -DHAVE_GETPEERNAME=0 -DHAVE_SOCKETPAIR=0 \
	-DHAVE_GETHOSTBYNAME=1 -DHAVE_GETHOSTBYNAME_R=0 \
	-DHAVE_FCNTL_O_NONBLOCK=1 -DHAVE_IOCTLSOCKET=0 -DHAVE_IOCTL_FIONBIO=0 \
	-DHAVE_GETIFADDRS=0 -DHAVE_IF_NAMETOINDEX=0 -DHAVE_PIPE=0 -DHAVE_EVENTFD=0 \
	-DHAVE_SIGACTION=0 -DHAVE_SIGNAL=0 -DHAVE_ALARM=0 -DHAVE_SIGSETJMP=0 \
	-DHAVE_GETPWUID=0 -DHAVE_GETPWUID_R=0 -DHAVE_GETEUID=0 -DHAVE_GETRLIMIT=0 -DHAVE_SETRLIMIT=0 \
	-DHAVE_UTIMES=0 -DHAVE_UTIME=0 -DHAVE_SCHED_YIELD=0 -DHAVE_SETMODE=0 -DHAVE_MSG_NOSIGNAL=0 \
	-DHAVE_SYS_UN_H=0 -DHAVE_LINUX_TCP_H=0 -DHAVE_NETINET_TCP_H=0 \
	-DHAVE_SOCKADDR_IN6_SIN6_SCOPE_ID=0 -DHAVE_STRUCT_SOCKADDR_STORAGE=1 \
	-DHAVE_CLOCK_GETTIME_MONOTONIC=0 -DHAVE_GETTIMEOFDAY=1

cmake --build "$BUILD" --parallel
cmake --install "$BUILD"
echo "libcurl $CURL_VER installed to $PREFIX"
